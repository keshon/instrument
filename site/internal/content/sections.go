package content

import "strings"

// Канонический контракт страницы компонента.
//
// До этого файла страница была потоком прозы с произвольными подзаголовками.
// На сорока семи компонентах это дало сто двадцать разных H2, из которых
// повторялись четыре: «Справочник», «Связанное», «Доступность», «Когда
// использовать». Остальные девяносто встречались ровно по одному разу —
// «Каретка», «Пульсация, а не блик», «Оговорённое исключение». Оглавление
// справа честно перечисляло весь этот шум, и узнать в нём страницу было
// нельзя: каждый компонент читался заново.
//
// Контракт закрывает словарь заголовков, а не список секций во frontmatter.
// Причина простая: frontmatter был бы вторым источником истины и разошёлся бы
// с телом на первой же правке. Здесь источник один — сам заголовок, — а
// словарь только УЗНАЁТ его и приписывает секции устойчивый идентификатор,
// порядок и перевод.
//
// Три следствия, ради которых всё и затевалось:
//
//   - якорь перестал зависеть от языка. Был `#варианты` в русской версии и
//     `#variants` в английской — то есть ссылка на раздел ломалась при смене
//     языка. Стал `#variants` в обеих;
//   - порядок разделов проверяется машиной. «Доступность» выше «Вариантов» —
//     это не мнение автора, это ошибка сборки;
//   - страница не обязана иметь все шестнадцать разделов. Обязательные
//     проверяются, остальные появляются по надобности. Иначе через полгода у
//     спиннера завёлся бы раздел «Когда не использовать» из одной фразы,
//     потому что шаблон велел.
//
// Секции НЕ обязательны все сразу. У кнопки их четырнадцать, у спиннера
// восемь, у модалки свои — с «Устройством» и «Поведением».
type SectionDef struct {
	ID    string
	Order int

	// Aliases — заголовки, по которым секция узнаётся. Первый — канонический
	// русский, дальше идут английский и исторические варианты, которые уже
	// стоят в страницах и переписывать которые ради узнавания незачем.
	Aliases []string
}

// Порядок здесь — это ПОРЯДОК ЧТЕНИЯ, и он же проверяется сборкой.
//
// Сначала «что это и как это запустить», потом «правильный ли это выбор»,
// потом поверхность компонента от простого к сложному, потом правила и
// доступность, и только в конце — полная техническая поверхность. Справочник
// стоит последним не потому, что он неважен, а потому, что за ним не приходят
// первым: за ним возвращаются.
var sectionDefs = []SectionDef{
	{"install", 10, []string{"Установка", "Installation"}},
	{"usage", 20, []string{"Использование", "Usage", "Разметка", "Контракт разметки", "Разметка обязательна"}},
	{"when", 30, []string{"Когда использовать", "When to use"}},
	{"anatomy", 40, []string{"Устройство", "Anatomy", "Части", "Пункты"}},

	// Шкала — раздел ОСНОВАНИЙ, а не компонентов.
	//
	// У основания есть то, чего у компонента нет: перечисление значений.
	// Рампы цвета, ступени пространства, длительности движения, четыре
	// поверхности, ярусы токенов — это не «варианты» и не «устройство», это
	// сам материал, выложенный целиком. Раздел стоит между устройством и
	// вариантами: сначала из чего сделано, потом сколько его бывает, потом
	// чем оно отличается от темы к теме.
	{"scale", 45, []string{"Шкала", "Scale", "Значения", "Values"}},

	{"variants", 50, []string{"Варианты", "Variants", "Модификаторы", "Тон", "Тона", "Темы"}},
	{"sizes", 60, []string{"Размеры", "Sizes"}},
	{"states", 70, []string{"Состояния", "States"}},
	{"icons", 80, []string{"С иконкой", "With icon", "Иконки"}},
	{"behavior", 90, []string{"Поведение", "Behavior", "Behaviour"}},

	// JS — отдельный раздел, а не подраздел «Поведения».
	//
	// «Поведение» отвечает на «что происходит», JS — на «что для этого вызвать».
	// Это разные вопросы и разные читатели: первый приходит понять компонент,
	// второй — подключить его. Смешанные в один раздел, они дают страницу, где
	// сигнатура функции лежит между двумя абзацами рассуждения.
	{"js", 95, []string{"JS", "JavaScript", "Скрипт"}},
	{"composition", 100, []string{"Композиции", "Composition", "Композиция"}},
	{"patterns", 110, []string{"Сценарии", "Patterns", "Собранный экран"}},
	{"rules", 120, []string{"Правила", "Rules"}},
	{"a11y", 130, []string{"Доступность", "Accessibility"}},
	{"customization", 140, []string{"Настройка", "Customization", "Свой вариант"}},
	{"api", 150, []string{"API", "Справочник", "API Reference"}},
	{"related", 160, []string{"Связанное", "Related"}},
}

// byAlias строится один раз: заголовок → определение секции.
var byAlias = func() map[string]*SectionDef {
	m := map[string]*SectionDef{}
	for i := range sectionDefs {
		d := &sectionDefs[i]
		for _, a := range d.Aliases {
			m[normTitle(a)] = d
		}
	}
	return m
}()

var byID = func() map[string]*SectionDef {
	m := map[string]*SectionDef{}
	for i := range sectionDefs {
		m[sectionDefs[i].ID] = &sectionDefs[i]
	}
	return m
}()

// normTitle приводит заголовок к виду, по которому его ищут: регистр и
// хвостовые пробелы не должны решать, узнана секция или нет.
func normTitle(s string) string {
	return strings.ToLower(strings.Join(strings.Fields(s), " "))
}

// LookupSection узнаёт секцию по тексту заголовка.
func LookupSection(title string) (*SectionDef, bool) {
	d, ok := byAlias[normTitle(title)]
	return d, ok
}

// SectionByID — определение по идентификатору. Нужно проверке: она говорит о
// секциях идентификаторами, а не заголовками.
func SectionByID(id string) (*SectionDef, bool) {
	d, ok := byID[id]
	return d, ok
}

// Section — секция, найденная НА СТРАНИЦЕ. Порядок — порядок в документе.
type Section struct {
	ID    string // variants · api · или автоидентификатор незнакомого заголовка
	Title string // как напечатано на странице, уже на её языке
	Order int    // из словаря; 0 у незнакомого заголовка
	Known bool
}
