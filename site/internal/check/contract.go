package check

import (
	"fmt"
	"sort"
	"strings"

	"instrument/site/internal/content"
	"instrument/site/internal/i18n"
)

// Contract проверяет канонический контракт страницы компонента.
//
// Смысл в том, чтобы документация имела собственный CI, а не надежду автора не
// забыть. Красивый Markdown-вьюер отличается от дизайн-системы ровно этим: в
// дизайн-системе «у стабильного компонента нет раздела API» — это красная
// сборка, а не наблюдение, сделанное через полгода случайно.
//
// Проверяются две вещи разной строгости:
//
//	errors    страница объявила `layout: component` — контракт обязателен;
//	warnings  страница ещё не переносена — сообщаем, что мешает переносу,
//	          но сборку не роняем. Иначе перенос сорока семи компонентов был
//	          бы «всё или ничего», то есть не начался бы никогда.
//
// Проверка идёт по РУССКОЙ версии: английская — это тот же файл, и вторая
// копия каждой жалобы ничего не добавляет.

// required — разделы, без которых страница компонента не документация.
//
// Ровно четыре, и каждый отвечает на вопрос, с которым приходят:
//
//	usage    что скопировать, чтобы заработало;
//	a11y     сломает ли это клавиатуру и скринридер;
//	api      полная техническая поверхность;
//	related  что смотреть дальше.
//
// «Варианты», «Размеры», «Состояния» в список НЕ входят намеренно. У спиннера
// нет вариантов, и раздел «Варианты» из одной фразы «вариантов нет» — это
// шаблон, победивший здравый смысл.
var required = []string{"usage", "a11y", "api", "related"}

// underContract — каталоги, страницы которых обязаны прийти к контракту.
//
// about и internal сюда не входят: конституция и процессные документы — это
// проза о проекте, а не описание поверхности. Раздел «API» у конституции был
// бы шаблоном, победившим здравый смысл.
func underContract(dir string) bool {
	for _, p := range []string{"components/", "foundations", "layout", "agent"} {
		if strings.HasPrefix(dir, p) {
			return true
		}
	}
	return false
}

func Contract(pages []*content.Page) (errs, warns []string) {
	for _, p := range pages {
		if p.Lang != i18n.RU || p.Splash || p.Slug == "index" {
			continue
		}
		// Два вида страницы под контрактом, и различие не косметическое.
		//
		//	component   компонент: его ВЫБИРАЮТ среди альтернатив, поэтому
		//	            «Когда использовать» отвечает на «а не взять ли
		//	            другое», и раздел «Шкала» ему не нужен;
		//	foundation  основание: цвет, пространство, движение. Его не
		//	            выбирают — он материал, из которого сделано всё
		//	            остальное. У него есть «Шкала» — перечисление
		//	            значений целиком, — и её нет ни у одного компонента.
		//
		// Обязательный набор у обоих один и тот же: за usage, a11y, api и
		// related приходят одинаково.
		strict := p.Layout == "component" || p.Layout == "foundation"

		// Страницы вне контракта получают замечания, а не ошибки. Каталоги
		// перечислены явно: about — это конституция и процессные тексты, у
		// них другая природа, и загонять их в контракт компонента незачем.
		if !strict && !underContract(p.Dir) {
			continue
		}

		var out []string

		// 1. Незнакомый заголовок. На перенесённой странице это ошибка: словарь
		//    закрыт, и «Пульсация, а не блик» уровня H2 — это подраздел,
		//    заблудившийся на уровень выше.
		for _, s := range p.Sections {
			if !s.Known {
				out = append(out, fmt.Sprintf("%s  раздел %q не из словаря (сделайте его H3 внутри канонического раздела)",
					p.Route, s.Title))
			}
		}

		// 2. Порядок чтения. «Доступность» выше «Вариантов» — не мнение автора,
		//    а перепутанные разделы: страница обязана читаться сверху вниз
		//    одинаково на всех компонентах.
		prev, prevID := 0, ""
		for _, s := range p.Sections {
			if !s.Known {
				continue
			}
			if s.Order < prev {
				out = append(out, fmt.Sprintf("%s  раздел %q стоит после %q, а должен перед ним",
					p.Route, s.ID, prevID))
			}
			prev, prevID = s.Order, s.ID
		}

		// 3. Повтор. Два «Состояния» на одной странице — это раздел, забытый
		//    при правке, и оглавление с двумя одинаковыми пунктами.
		seen := map[string]bool{}
		for _, s := range p.Sections {
			if s.Known && seen[s.ID] {
				out = append(out, fmt.Sprintf("%s  раздел %q встречается дважды", p.Route, s.ID))
			}
			seen[s.ID] = true
		}

		// 4. Обязательные разделы и главный пример.
		for _, id := range required {
			if !seen[id] {
				out = append(out, fmt.Sprintf("%s  нет обязательного раздела %q", p.Route, id))
			}
		}
		if !p.Hero {
			out = append(out, p.Route+"  нет главного примера: живой пример обязан стоять в шапке, до первого раздела")
		}

		if strict {
			errs = append(errs, out...)
		} else {
			warns = append(warns, out...)
		}
	}
	sort.Strings(errs)
	sort.Strings(warns)
	return errs, warns
}
